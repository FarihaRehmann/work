const dateTabs = document.getElementById("dateTabs");
const taskContainer = document.getElementById("taskContainer");
const dayTitle = document.getElementById("dayTitle");
const dayQuote = document.getElementById("dayQuote");
const progressNumber = document.getElementById("progressNumber");
const progressFill = document.getElementById("progressFill");
const taskCount = document.getElementById("taskCount");
const resetButton = document.getElementById("resetButton");

let selectedDay = 0;

function getSavedTasks() {
  return JSON.parse(localStorage.getItem("studyPlannerTasks")) || {};
}

function saveTasks(tasks) {
  localStorage.setItem("studyPlannerTasks", JSON.stringify(tasks));
}

function getDayTasks(dayIndex) {
  return schedule[dayIndex].sections.flatMap(section => section.tasks);
}

function renderTabs() {
  dateTabs.innerHTML = "";

  schedule.forEach((day, index) => {
    const button = document.createElement("button");
    button.className = `date-tab ${index === selectedDay ? "active" : ""}`;
    button.innerHTML = `
      <span>${day.day.slice(0, 3)}</span>
      ${day.date.split(" ")[0]}
    `;

    button.addEventListener("click", () => {
      selectedDay = index;
      renderTabs();
      renderDay();
    });

    dateTabs.appendChild(button);
  });
}

function renderDay() {
  const day = schedule[selectedDay];
  const savedTasks = getSavedTasks();
  const dayKey = day.date;
  const completedTasks = savedTasks[dayKey] || {};

  dayTitle.textContent = `${day.day}, ${day.date}`;
  dayQuote.textContent = day.quote;

  taskContainer.innerHTML = "";

  day.sections.forEach((section, sectionIndex) => {
    const card = document.createElement("section");
    card.className = "task-card";

    const heading = document.createElement("h3");
    heading.textContent = section.title;
    card.appendChild(heading);

    section.tasks.forEach((task, taskIndex) => {
      const taskId = `${sectionIndex}-${taskIndex}`;
      const label = document.createElement("label");
      label.className = "task";

      const checkbox = document.createElement("input");
      checkbox.type = "checkbox";
      checkbox.checked = Boolean(completedTasks[taskId]);

      const text = document.createElement("span");
      text.textContent = task;

      if (checkbox.checked) {
        label.classList.add("completed");
      }

      checkbox.addEventListener("change", () => {
        const latestTasks = getSavedTasks();

        if (!latestTasks[dayKey]) {
          latestTasks[dayKey] = {};
        }

        latestTasks[dayKey][taskId] = checkbox.checked;
        saveTasks(latestTasks);

        label.classList.toggle("completed", checkbox.checked);
        updateProgress();
      });

      label.appendChild(checkbox);
      label.appendChild(text);
      card.appendChild(label);
    });

    taskContainer.appendChild(card);
  });

  updateProgress();
}

function updateProgress() {
  const day = schedule[selectedDay];
  const completedTasks = getSavedTasks()[day.date] || {};

  const total = getDayTasks(selectedDay).length;
  const done = Object.values(completedTasks).filter(Boolean).length;
  const percentage = total === 0 ? 0 : Math.round((done / total) * 100);

  progressNumber.textContent = `${percentage}%`;
  progressFill.style.width = `${percentage}%`;
  taskCount.textContent = `${done} / ${total} tasks`;
}

resetButton.addEventListener("click", () => {
  const day = schedule[selectedDay];
  const savedTasks = getSavedTasks();

  if (confirm(`Reset all progress for ${day.date}?`)) {
    delete savedTasks[day.date];
    saveTasks(savedTasks);
    renderDay();
  }
});

renderTabs();
renderDay();
